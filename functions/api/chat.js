export async function onRequestPost({ request, env }) {
  try {
    const body = await request.json();
    const message = String(body?.message || "").trim();
    if (!message || message.length > 5000) {
      return Response.json({ error: "Сообщение пустое или слишком длинное." }, { status: 400 });
    }
    if (!env.AI) {
      return Response.json({
        reply: "Я получил описание ситуации. Чтобы подготовить содержательный разбор, нужно подключить Cloudflare Workers AI и проверяемые источники законодательства РФ. Пока уточни: когда произошла ситуация, в каком регионе РФ и какие документы или ответы у тебя есть? Не присылай персональные данные. Это не юридическое заключение."
      });
    }
    const result = await env.AI.run("@cf/meta/llama-3.1-8b-instruct", {
      messages: [
        { role: "system", content: "Ты — Cat Lawyer, информационный помощник по праву Российской Федерации. Отвечай по-русски простым языком. Сначала выявляй факты и задавай уточняющие вопросы. Не выдумывай статьи, судебную практику, сроки и реквизиты органов. Если не уверен в действующей редакции нормы, прямо скажи, что её нужно проверить по официальному источнику. Разделяй установленные факты, предположения и рекомендации. Не выдавай ответ за юридическое заключение. Не проси паспортные, банковские и иные лишние персональные данные. Если ситуация срочная или связана с угрозой жизни, здоровью либо сроком обжалования, посоветуй обратиться к профильному специалисту." },
        { role: "user", content: message }
      ],
      max_tokens: 650
    });
    return Response.json({ reply: result.response || "Не удалось подготовить ответ. Попробуй ещё раз." });
  } catch {
    return Response.json({ error: "Ошибка обработки запроса." }, { status: 500 });
  }
}